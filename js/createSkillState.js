// Состояние навыков в бою (сохраняется вместе с боем).
function createSkillState() {
  return {
    used: {},            // id активных навыков «раз за бой», которые уже применены
    triggered: {},       // разовые пассивные срабатывания (lowHp, shieldBroken, gather once)
    heroTurns: 0,        // сколько ходов сделал игрок
    steps: 0,            // сколько серий (с каскадами) в текущем ходе
    wards: [],           // защиты: { pct, hits } или { pct, turns } — ослабляют урон врага
    dmgReduce: 0,        // постоянное снижение урона врага до конца боя, %
    firstHitDone: false, // первый удар врага уже был
    buff: null,          // { pct, turns } — усиление ваших ходов
    pendingPct: 0,       // разовое усиление следующей серии (после навыка, первая серия боя)
    lastEnemyLoss: { hp: 0, shield: 0 }, // что отнял последний ход врага (для «Разрыва хронологии»)
    notes: 0             // «Пометки на полях», собранные в этом бою
  };
}
