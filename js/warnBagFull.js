// Перед боем: если в сумках не осталось места — предупредить, что добыча упадёт на землю и её разворуют;
// осталась одна ячейка — напомнить, что скоро так и будет.
function warnBagFull(hero) {
  const free = bagFreeSlots(hero);
  if (free <= 0) {
    logBattle('sys', 'Сумка полна: добыча упадёт на землю.');
    showToast('Сумка набита под завязку! Всё, что выпадет, упадёт на землю — и местные разворуют это быстрее, чем вы скажете «моё». Разгрузитесь у Семёныча.', 4500);
  } else if (free === 1) {
    showToast('В сумке осталось одно место. Дальше добыча полетит на землю — на радость мародёрам.', 3500);
  }
}
