// Глоссарий · Реестр Героев и Пострадавших (js/paragonConfig.js): как получают очки и все компенсации.
function glossaryParagon() {
  return [glossaryEntry(PARAGON_ICON, PARAGON_NAME, tr("ui.Общий для аккаунта · в лагере"), [
    tr("ui.Официальная система, где герой одновременно числится героем и пострадавшим от ЧС. Бонусы выдаются как компенсации."),
    tr("ui.1 очко — за каждые ") + PARAGON_LEVEL_STEP + tr("ui. уровней любого вашего персонажа. Компенсации получают все персонажи сразу."),
    tr("ui.Оформлять можно только рядом с уже оформленной (от «Заявления о признании»). «Аннулировать всё» возвращает очки.")]),
  ...PARAGON_NODES.map(n => glossaryEntry('', tr("ui.Компенсация № ") + n.no + ': ' + n.name, tr("ui.до ") + n.max + ' ' + plural(n.max, tr("ui.ранга"), tr("ui.рангов"), tr("ui.рангов")),
    [tr("ui.За ранг: ") + paragonEffectText(n).replace(/\.$/, '') + '.', ['lore', tr("ui.Причина: ") + n.reason + '.']]))];
}
